from functools import lru_cache

from pydantic_settings import BaseSettings, SettingsConfigDict


class Settings(BaseSettings):
    model_config = SettingsConfigDict(env_file=".env", extra="ignore")

    env: str = "dev"  # dev / prod
    database_url: str = "postgresql+psycopg://leadgen:leadgen@db:5432/leadgen"

    # Auth
    secret_key: str = "change-me-in-prod"
    access_token_minutes: int = 30
    refresh_token_days: int = 14
    cookie_secure: bool = False  # True behind HTTPS in prod
    login_rate_per_minute: int = 10

    # Encryption of integration tokens at rest (Fernet key; generated by `manage.py gen-key`)
    fernet_key: str = ""

    # LLM defaults (an organization can override in settings)
    llm_base_url: str = "http://host.docker.internal:8080/v1"
    llm_model: str = ""
    llm_api_key: str = "local"
    llm_disable_thinking: bool = True

    # Sources
    searxng_url: str = "http://searxng:8080"
    vk_api_version: str = "5.199"

    # Worker
    worker_poll_seconds: float = 2.0
    worker_concurrency: int = 1


@lru_cache
def get_settings() -> Settings:
    return Settings()


settings = get_settings()
